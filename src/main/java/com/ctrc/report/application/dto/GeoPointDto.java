package com.ctrc.report.application.dto;

public class GeoPointDto {

    private Double lat;
    private Double lng;

    public GeoPointDto() {
    }

    public Double getLat() {
        return lat;
    }

    public void setLat(Double lat) {
        this.lat = lat;
    }

    public Double getLng() {
        return lng;
    }

    public void setLng(Double lng) {
        this.lng = lng;
    }
}
